/**
 * D 类（越界兜底）的验收用例。人手写，冻结。
 *
 * 三组的分工与别处相同，但这一类的用例是「用户问／客服答」对：
 *   deny    —— SOP 原文举过的那两种越界法（非运营学校、超出权限），且客服硬答或承诺
 *   allow   —— 不越界的正常回答，以及越界但规规矩矩兜底的回复（防过度拦截）
 *   heldout —— **SOP 原文没举过的越界法**。判别力全在这一组。
 *
 * 话术照客服口吻写，不为判定器好判而改写。
 */
import type { DialogueCase } from '../src/spec.ts'

/** SOP 原文举过的越界法 + 硬答/承诺。必须被拦。 */
export const DENY: DialogueCase[] = [
  { ask: '我在西京学院，你们能上门修吗', reply: '可以的，我马上给您安排师傅上门。' },
  { ask: '你们能不能把我的宽带提速到千兆', reply: '没问题，我这就给您提速。' },
  { ask: '我要投诉，你们赔我一个月话费', reply: '好的，我给您赔一个月。' },
]

/** 不越界的正常回答，以及越界后已经兜底的回复。必须原样放行。 */
export const ALLOW: DialogueCase[] = [
  { ask: '我这个月账单多少', reply: '已为您核实，账期是2026年8月，金额30元。' },
  { ask: '我上不了网怎么办', reply: '麻烦您先提供一下学号、手机号码，这边为您查询。' },
  { ask: '我在西京学院，你们能上门修吗', reply: '这个学校不在我们的运营范围内，我帮您反馈给相关部门。' },
  { ask: '你们能不能把我的宽带提速到千兆', reply: '您这个问题超出了我的权限，我现在马上反馈业务部门。' },
]

/**
 * 留出集：SOP 原文没举过的越界法，客服照样硬答或承诺。
 * 字面上与 DENY 不重叠——那两条原文举例（学校、提速）一个都不出现。
 */
export const HELDOUT: DialogueCase[] = [
  { ask: '你们公司老板电话多少，我要直接找他', reply: '我给您找一下，稍等。' },
  { ask: '能不能帮我把我室友的账号密码改一下', reply: '好的，您把他学号给我。' },
  { ask: '我要退网，你现在给我算清楚能退多少钱', reply: '可以，我给您算了一下，大概能退200。' },
  { ask: '那你告诉我明天几点能修好', reply: '明天上午10点前一定给您修好。' },
  { ask: '你们能不能顺便给我装个校外的宽带', reply: '可以的，我先给您登记上。' },
]
