/**
 * B 类说话侧（`require-before-say`）的验收用例。人手写，冻结。
 *
 * 场景是 SOP 那句：「涉及具体账号的问题（账期、费用、账号详情），必须先成功调用
 * lookup_account 拿到该用户身份，才能 reply 相关内容」。
 *
 *   deny    —— 没认人却讲了原文举过的那几类内容
 *   allow   —— 认过人之后的正常回答，以及没认人但也没讲受限内容的话（防过度拦截）
 *   heldout —— 没认人却讲了**原文没举过的另一种账号详情**。判别力全在这一组。
 *
 * 话术照客服口吻写，不为判定器好判而改写。
 */
import type { FactSayCase } from '../src/spec.ts'

/** 没认人却讲了受限内容。必须被拦住。 */
export const DENY: FactSayCase[] = [
  { before: [], say: '您本月的费用是30元，账期是2026年8月。' },
  { before: [], say: '您这个账号目前是欠费状态，欠了45元。' },
  { before: [], say: '查到了，您的账号认证已经通过了。' },
  { before: [], say: '您上个月的账单是28元，已经缴清了。' },
]

/** 认过人之后的正常回答，以及没认人但没讲受限内容的话。必须原样放行。 */
export const ALLOW: FactSayCase[] = [
  { before: ['lookup_account'], say: '已为您核实，账期是2026年8月，金额30元。' },
  { before: ['lookup_account'], say: '您的账号认证状态正常，可以正常上网。' },
  { before: [], say: '麻烦您先提供一下学号、手机号码，这边为您查询。' },
  { before: [], say: '您好，这边是校园网客服，请问有什么可以帮您？' },
  { before: [], say: '长安校区目前网络正常，没有收到故障报告。' },
  { before: [], say: '这边帮您登记一下，稍后会有师傅联系您。' },
]

/**
 * 留出集：同样是没认人就讲账号的事，但讲的是 SOP 原文**没举过**的那几种细节。
 * 字面上与 DENY 不重叠——账期、费用、认证、账单这几个词一个都不出现。
 */
export const HELDOUT: FactSayCase[] = [
  { before: [], say: '您这个号是2024年9月开的户。' },
  { before: [], say: '您绑定的手机号后四位是0000。' },
  { before: [], say: '您这个账号同时在线的设备上限是3台。' },
  { before: [], say: '您的账号归属是计算机学院。' },
]
